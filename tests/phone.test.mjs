import test from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";

/*
 * Бэкенд на CommonJS — берётся из собранного dist: его импорты без расширений
 * ESM-загрузчик не разрешает. Заодно проверяется ровно то, что поедет
 * на сервер. Сборку делает pretest.
 */
const require = createRequire(import.meta.url);
const { normalizePhone } = require("../dist/shared/lib/normalizePhone.js");

/*
 * Разбор телефона написан дважды: здесь и во фронтенде (areve-frontend),
 * чтобы родитель видел ошибку не дожидаясь сервера. Репозитории разные,
 * общего кода нет, поэтому договор записан таблицей ниже.
 *
 * ЭТОТ ЖЕ НАБОР ЛЕЖИТ В areve-frontend. Меняете правило — меняйте в обоих.
 */

const VALID = [
  // как их дал центр
  ["095 313 633", "+37495313633"],
  ["094 505 552", "+37494505552"],
  // те же номера в других записях
  ["+374 95 313 633", "+37495313633"],
  ["+37495313633", "+37495313633"],
  ["37495313633", "+37495313633"],
  ["0-95-31-36-33", "+37495313633"],
  ["(095) 313-633", "+37495313633"],
  // без кода страны и без ведущего нуля
  ["95313633", "+37495313633"],
];

const INVALID = [
  "",
  "   ",
  "123",
  "095 313 63", // на цифру короче
  "0953136330", // на цифру длиннее
  "+7 999 123 45 67", // российский номер
  "abc",
];

test("нормализация приводит номер к +374XXXXXXXX", () => {
  for (const [input, expected] of VALID) {
    assert.equal(normalizePhone(input), expected, `вход: ${JSON.stringify(input)}`);
  }
});

test("непохожее на армянский номер отвергается", () => {
  for (const input of INVALID) {
    assert.equal(normalizePhone(input), null, `вход: ${JSON.stringify(input)}`);
  }
});

test("разные записи одного номера дают одну строку", () => {
  // Иначе один и тот же родитель выглядел бы в списке заявок как несколько разных.
  const same = ["095 313 633", "+374 95 313 633", "+37495313633", "0-95-31-36-33"];
  const results = new Set(same.map(normalizePhone));
  assert.equal(results.size, 1, `получилось разное: ${[...results].join(", ")}`);
});

test("номер на цифру короче не принимается за номер без кода страны", () => {
  /*
   * Ошибка, которую этот случай однажды поймал: «095 313 63» — восемь цифр
   * с ведущим нулём — считалось номером без кода страны, и ноль уезжал
   * в код оператора, давая +37409531363. Заявка сохранилась бы
   * с несуществующим телефоном: перезвонить по ней некому.
   */
  assert.equal(normalizePhone("095 313 63"), null);
  assert.equal(normalizePhone("37409531363"), null);
});
